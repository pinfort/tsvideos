-- Apply after 076 (#112), before deploying a build that contains it (idempotent; one ALTER, so file stays unique
-- throughout). Replaces created_file's long UNIQUE KEY file USING HASH with a plain unique index on a stored SHA-256 of
-- file. MariaDB checks a USING HASH key by a locking read of its hidden hash index, which leaves a gap lock until the
-- transaction ends even when nothing matches; two registrations of unrelated paths whose hashes fall in the same gap
-- then wait for each other's commit and can deadlock (each insert waiting on the other's gap lock). An ordinary unique
-- index takes no lock unless an equal key exists, so writers of different files never wait for each other.
-- RTRIM keeps the old key's equality: file is utf8mb4_bin, a PAD SPACE collation, so trailing spaces never told two
-- files apart. Generated by the server, so rows written by SQL outside catalog are covered as well.
ALTER TABLE created_file
 ADD COLUMN IF NOT EXISTS file_hash BINARY(32) AS (UNHEX(SHA2(RTRIM(file), 256))) STORED,
 ADD UNIQUE INDEX IF NOT EXISTS file_hash (file_hash),
 DROP INDEX IF EXISTS file;
