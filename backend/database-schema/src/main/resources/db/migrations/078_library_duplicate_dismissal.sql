-- Duplicate groups an operator confirmed as intentional and hid from the duplicate review (#194); see
-- backend/docs/duplicate-review.md. Apply before deploying a manager build that contains it (idempotent).
-- A row is identified by the detector's reason plus the group's exact program IDs, sorted and comma-separated
-- ("1,2,3"). A group whose membership or reason changes no longer matches any row and is shown for review again;
-- such rows are left in place and are harmless. program_ids deliberately has no FK to program: removing a member must
-- not shrink a stored identity into a different, smaller group. group_key is generated by the server so the unique
-- index stays short however many members a group has.
CREATE TABLE IF NOT EXISTS library_duplicate_dismissal (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 reason VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 program_ids TEXT CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 group_key BINARY(32) AS (UNHEX(SHA2(CONCAT(reason, ':', program_ids), 256))) STORED,
 dismissed_at DATETIME(6) NOT NULL,
 UNIQUE KEY library_duplicate_dismissal_group (group_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
